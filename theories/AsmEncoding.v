Definition asm_decode' : u8 -> itree M instr :=
  fun op => match op with
  | 0x00 => ret $[NOP]
  | 0x01 => w <- fetch16;; ret $[LDW BC, #w]
  | 0x02 => ret $[LD [BC], A]
  | 0x03 => ret $[INCW BC]
  | 0x04 => ret $[INC B]
  | 0x05 => ret $[DEC B]
  | 0x06 => b <- fetch;; ret $[LD B, #b]
  | 0x07 => ret $[RLCA]
  | 0x08 => w <- fetch16;; ret $[LDW [#w], SP]
  | 0x09 => ret $[ADD HL, BC]
  | 0x0A => ret $[LD A, [BC]]
  | 0x0B => ret $[DECW BC]
  | 0x0C => ret $[INC C]
  | 0x0D => ret $[DEC C]
  | 0x0E => b <- fetch;; ret $[LD C, #b]
  | 0x0F => ret $[RRCA]
  | 0x10 => ret $[STOP]
  | 0x11 => w <- fetch16;; ret $[LDW DE, #w]
  | 0x12 => ret $[LD [DE], A]
  | 0x13 => ret $[INCW DE]
  | 0x14 => ret $[INC D]
  | 0x15 => ret $[DEC D]
  | 0x16 => b <- fetch;; ret $[LD D, #b]
  | 0x17 => ret $[RLA]
  | 0x18 => b <- fetch;; ret $[JR #b]
  | 0x19 => ret $[ADD HL, DE]
  | 0x1A => ret $[LD A, [DE]]
  | 0x1B => ret $[DECW DE]
  | 0x1C => ret $[INC E]
  | 0x1D => ret $[DEC E]
  | 0x1E => b <- fetch;; ret $[LD E, #b]
  | 0x1F => ret $[RRA]
  | 0x20 => b <- fetch;; ret $[JR FNZ, #b]
  | 0x21 => w <- fetch16;; ret $[LDW HL, #w]
  | 0x22 => ret $[LD [HL+], A]
  | 0x23 => ret $[INCW HL]
  | 0x24 => ret $[INC H]
  | 0x25 => ret $[DEC H]
  | 0x26 => b <- fetch;; ret $[LD H, #b]
  | 0x27 => ret $[DAA]
  | 0x28 => b <- fetch;; ret $[JR FZ, #b]
  | 0x29 => ret $[ADD HL, HL]
  | 0x2A => ret $[LD A, [HL+]]
  | 0x2B => ret $[DECW HL]
  | 0x2C => ret $[INC L]
  | 0x2D => ret $[DEC L]
  | 0x2E => b <- fetch;; ret $[LD L, #b]
  | 0x2F => ret $[CPL]
  | 0x30 => b <- fetch;; ret $[JR FNC, #b]
  | 0x31 => w <- fetch16;; ret $[LDW SP, #w]
  | 0x32 => ret $[LD [HL-], A]
  | 0x33 => ret $[INCW SP]
  | 0x34 => ret $[INC [HL]]
  | 0x35 => ret $[DEC [HL]]
  | 0x36 => b <- fetch;; ret $[LD [HL], #b]
  | 0x37 => ret $[SCF]
  | 0x38 => b <- fetch;; ret $[JR FC, #b]
  | 0x39 => ret $[ADD HL, SP]
  | 0x3A => ret $[LD A, [HL-]]
  | 0x3B => ret $[DECW SP]
  | 0x3C => ret $[INC A]
  | 0x3D => ret $[DEC A]
  | 0x3E => b <- fetch;; ret $[LD A, #b]
  | 0x3F => ret $[CCF]
  | 0x40 => ret $[LD B, B]
  | 0x41 => ret $[LD B, C]
  | 0x42 => ret $[LD B, D]
  | 0x43 => ret $[LD B, E]
  | 0x44 => ret $[LD B, H]
  | 0x45 => ret $[LD B, L]
  | 0x46 => ret $[LD B, [HL]]
  | 0x47 => ret $[LD B, A]
